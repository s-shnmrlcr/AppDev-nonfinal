@push('scripts')
    <script>
        const beneficiaryDocument = {
            name: @json($beneficiary['name']),
            dob: @json($beneficiary['dob']),
            sex: @json($beneficiary['sex']),
            idNumber: @json($beneficiary['id_number']),
        };
        const input = document.getElementById('documentInput'),
            scan = document.getElementById('scanButton'),
            preview = document.getElementById('documentPreview');
        input?.addEventListener('change', () => {
            if (!input.files[0]) return;
            document.getElementById('fileName').textContent = input.files[0].name;
            preview.classList.remove('hidden');
            scan.disabled = false;
        });
        scan?.addEventListener('click', () => {
            scan.disabled = true;
            scan.textContent = 'Scanning...';
            setTimeout(() => {
                scan.textContent = 'Scan Complete';
                document.getElementById('fileStatus').textContent =
                    'Quality check passed · Prototype result';
                document.getElementById('docName').textContent = beneficiaryDocument.name.toUpperCase();
                document.getElementById('docDob').textContent = beneficiaryDocument.dob;
                document.getElementById('docSex').textContent = beneficiaryDocument.sex;
                document.getElementById('docId').textContent = beneficiaryDocument.idNumber;
                ['nameResult', 'dobResult', 'sexResult', 'idResult'].forEach(id => {
                    document.getElementById(id).textContent = '✓ MATCH';
                    document.getElementById(id).classList.add('match');
                });
                document.getElementById('scoreBadge').textContent = '94% HIGH MATCH';
                scan.disabled = false;
            }, 1200);
        });
    </script>
@endpush
